/** 본문 표기를 [텍스트, 종류] 조각으로 나눈다. */
export function splitRuleText(
  text: string
): { text: string; kind: "plain" | "strong" | "pending" }[] {
  return text
    .split(/(\*\*.+?\*\*|\{\{.+?\}\})/)
    .filter(Boolean)
    .map((part) =>
      part.startsWith("**")
        ? { text: part.slice(2, -2), kind: "strong" as const }
        : part.startsWith("{{")
        ? { text: part.slice(2, -2), kind: "pending" as const }
        : { text: part, kind: "plain" as const }
    );
}

/** ①, ②, … */
const circled = (n: number) => String.fromCharCode(0x2460 + n - 1);

function articlePlainText(article: RuleArticle): string[] {
  const plain = (s: string) =>
    splitRuleText(s)
      .map((p) => (p.kind === "pending" ? `〔${p.text}〕` : p.text))
      .join("");
  const heading = [
    article.no ? `제${article.no}조` : "",
    article.title,
    `[${article.tags.map(([, label]) => label).join(" · ")}]`,
  ]
    .filter(Boolean)
    .join(" ");
  return [
    heading,
    ...article.clauses.map((c, i) => `${circled(i + 1)} ${plain(c)}`),
    ...(article.note ? [`※ 검토 메모: ${article.note}`] : []),
    "",
  ];
}

